#!/usr/bin/env node
/**
 * Generate packages/headpress/src/generated/store-config.ts from contract/.
 *
 *   node scripts/codegen.mjs          write the file
 *   node scripts/codegen.mjs --check  fail when the committed file is out of date (CI)
 *
 * One interface per core module (contract/core-modules.json) plus the commerce block. Schema
 * descriptions and titles are dropped: Headpress translates them with the site locale, so keeping
 * them would make the output depend on which site the contract was pulled from.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

import { compile } from "json-schema-to-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contractDir = join(root, "contract");
const target = join(root, "packages", "headpress", "src", "generated", "store-config.ts");

const { values } = parseArgs({ options: { check: { type: "boolean", default: false } } });

const read = (file) => JSON.parse(readFileSync(join(contractDir, file), "utf8"));
const schema = read("store-config.schema.json");
const commerce = read("commerce.schema.json");
const meta = existsSync(join(contractDir, "meta.json")) ? read("meta.json") : {};
const { modules: coreModules } = read("core-modules.json");

/** Drop locale-dependent and naming keys, and PHP's `[]` for an empty `properties`. */
function clean(node) {
  if (Array.isArray(node)) return node.map(clean);
  if (!node || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "description" || key === "title" || key === "$id" || key === "$schema") continue;
    if (key === "properties" && Array.isArray(value)) continue;
    out[key] = clean(value);
  }
  return out;
}

const pascal = (id) =>
  id
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

const options = {
  bannerComment: "",
  format: true,
  style: { printWidth: 100, semi: true, singleQuote: false, trailingComma: "all" },
  declareExternallyReferenced: true,
  strictIndexSignatures: false,
  unknownAny: true,
};

const moduleSchemas = schema.properties?.modules?.properties ?? {};
const missing = coreModules.filter((id) => !moduleSchemas[id]);
if (missing.length) {
  console.error(`Core modules missing from the contract: ${missing.join(", ")}`);
  process.exit(1);
}

const parts = [];
const mapEntries = [];
for (const id of coreModules) {
  const name = `${pascal(id)}ModuleConfig`;
  parts.push((await compile(clean(moduleSchemas[id]), name, options)).trim());
  mapEntries.push(`  ${id}: ${name};`);
}
parts.push((await compile(clean(commerce), "CommerceConfig", options)).trim());

const source = meta.headpress_version
  ? `Headpress ${meta.headpress_version}${meta.headpress_commit ? ` (${meta.headpress_commit}${meta.headpress_dirty ? ", uncommitted changes" : ""})` : ""}`
  : "an unrecorded Headpress version";

const output = `/* eslint-disable */
/**
 * Generated by scripts/codegen.mjs from contract/ — do not edit by hand.
 * Contract pulled from ${source}.
 */

${parts.join("\n\n")}

/** Public config of each Headpress core module, keyed by module id. */
export interface CoreModuleConfigMap {
${mapEntries.join("\n")}
}
`;

if (values.check) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== output) {
    console.error("src/generated/store-config.ts is out of date. Run `pnpm codegen` and commit the result.");
    process.exit(1);
  }
  console.log("Generated types are up to date.");
} else {
  writeFileSync(target, output);
  console.log(`Wrote ${target} (${coreModules.length} modules).`);
}
